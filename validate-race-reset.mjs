import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {nearestTrackPose} from './track-reset.js';
import {Vec3} from './vendor/cannon-es.js';
const source=readFileSync(new URL('./main.js',import.meta.url),'utf8');
const resetSource=source.slice(source.indexOf('function resetToTrack(){'),source.indexOf("$('reset-track').onclick"));
const lockSource=source.match(/onLock:state=>\{([^\n]+)\},/)[1];
const lock={race:true,freeze:false},keys=new Set(['KeyW']),elements=new Map();
const $=id=>{if(!elements.has(id))elements.set(id,{});return elements.get(id);};
const trail=[{x:0,z:0},{x:0,z:100}],routes=[{points:[{x:25,z:0},{x:25,z:100}]}];
const chassis={position:new Vec3(29,2,60),quaternion:{vmult:v=>v}},poses=[];
const run=new Function('networkLock','keys','chassis','C','nearestTrackPose','testingGround','spawnPoint','reset','$',resetSource+';return resetToTrack;')(lock,keys,chassis,{Vec3},nearestTrackPose,{meta:{trail,routes}},{x:99,z:99,yaw:0},pose=>poses.push(pose),$);
const onLock=new Function('networkLock','$','carLoading','state',lockSource);
onLock(lock,$,false,{race:true,freeze:false,vehicle:true});
assert.equal($('reset-track').disabled,false,'reset button is enabled during a race');
run();assert.equal(poses.length,1,'race reset executes');assert.equal(poses[0].x,25);assert.equal(poses[0].z,60,'nearest track centre rather than race start');assert.equal(keys.size,0,'held throttle cleared');
onLock(lock,$,false,{race:true,freeze:true,vehicle:true});assert.equal($('reset-track').disabled,true,'grid remains fixed during countdown or disconnection');run();assert.equal(poses.length,1,'R key respects the same countdown freeze');
onLock(lock,$,false,{race:false,freeze:false,vehicle:false});run();assert.equal(poses.length,2,'solo reset is unchanged');
assert(source.includes("$('reset-track').onclick=resetToTrack"));assert(source.includes("e.code==='KeyR')resetToTrack()"));
console.log('Passed: race button and R reset to nearest track; countdown/disconnection freeze; solo recovery.');
